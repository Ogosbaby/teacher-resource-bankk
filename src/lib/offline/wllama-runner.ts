/**
 * In-browser WebAssembly LLM Inference Runner using @wllama/wllama.
 *
 * Runs the Qwen GGUF model in-memory inside the client browser or Capacitor app.
 * Built with safety guards: if memory is insufficient or wasm fails,
 * it safely throws so the caller can fall back to the Offline Curriculum Engine.
 */

import { getModelSink } from "./model-store";

let wllamaInstance: any = null;
let isInitializing = false;

export async function isWllamaSupported(): Promise<boolean> {
  if (typeof window === "undefined" || !("WebAssembly" in window)) {
    return false;
  }
  // Check if WebAssembly SIMD or Basic is available
  try {
    return typeof WebAssembly.validate === "function";
  } catch {
    return false;
  }
}

/**
 * Attempt to initialize wllama and run inference for the lesson plan.
 */
export async function runWllamaInference(prompt: string): Promise<string> {
  const supported = await isWllamaSupported();
  if (!supported) {
    throw new Error("WebAssembly inference not supported on this platform.");
  }

  // Check if we have bytes stored in our model sink
  const sink = await getModelSink();
  const received = await sink.bytesReceived();
  if (received < 10_000_000) {
    // Less than 10MB means the model hasn't been downloaded yet
    throw new Error("Local model is not yet downloaded into storage.");
  }

  const wllamaModule: any = await (new Function('return import("@wllama/wllama/esm/index.js")')());
  const Wllama = wllamaModule.Wllama || wllamaModule.default?.Wllama;

  if (!wllamaInstance) {
    if (isInitializing) {
      throw new Error("Model is currently loading into memory.");
    }
    isInitializing = true;
    try {
      // Configuration for wllama wasm assets — local first for true 100% offline support
      const localWasmUrl =
        typeof window !== "undefined"
          ? `${window.location.origin}/wasm/wllama.wasm`
          : "/wasm/wllama.wasm";

      wllamaInstance = new Wllama({
        default: localWasmUrl,
      }, {
        suppressNativeLog: true,
      });


      // Stream the stored bytes from sink to create a Blob
      const chunks: Uint8Array[] = [];
      await sink.readAll((chunk) => {
        chunks.push(chunk);
      });

      const modelBlob = new Blob(chunks as any, { type: "application/octet-stream" });
      await wllamaInstance.loadModel(modelBlob, {
        n_ctx: 1024,
      });
    } finally {
      isInitializing = false;
    }
  }

  const completion = await wllamaInstance.createChatCompletion({
    messages: [
      {
        role: "system",
        content: "You are an expert Nigerian curriculum instructional designer. Create comprehensive, structured lesson notes according to NERDC guidelines.",
      },
      {
        role: "user",
        content: prompt,
      },
    ],
    n_predict: 800,
    temperature: 0.3,
  });

  const responseText = completion?.choices?.[0]?.message?.content;
  if (!responseText) {
    throw new Error("No response generated by local model.");
  }
  return responseText;
}
