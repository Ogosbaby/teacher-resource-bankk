/**
 * Orders — the money side of the internal LMS.
 *
 * An order exists from the moment a customer commits to paying, and it is the
 * thing that ties together the three halves of a purchase: who paid (customer),
 * what the payment gateway said (provider reference + status), and what it
 * bought (subscription + activation code).
 *
 * It is written **before** the customer is sent to Paystack, so that the redirect
 * and the webhook both have a row to find. Both then move it to `paid` through
 * `markOrderPaid`, which is idempotent: the first caller wins and the second sees
 * the row it already wanted, because a redirect and a webhook routinely arrive
 * within milliseconds of each other and must not provision two terms.
 */
import { and, count, desc, eq, inArray, sql } from "drizzle-orm";
import { db } from "@/lib/db/client";
import { customers, orders, orderStatus, salesAgents, terms } from "@/lib/db/schema";

export type Order = typeof orders.$inferSelect;
export type OrderStatus = (typeof orderStatus.enumValues)[number];

export interface CreateOrderInput {
  reference: string;
  customerId: string;
  userId?: string | null;
  salesAgentId?: string | null;
  termId?: string | null;
  amountKobo: number;
  currency?: string;
  source?: string;
  providerReference?: string | null;
  authorizationUrl?: string | null;
  metadata?: Record<string, unknown>;
}

/**
 * Record intent to pay.
 *
 * `reference` is generated by the caller (see `generateOrderReference`) and is the
 * idempotency key shared with Paystack: both the redirect and the webhook arrive
 * carrying it, so it is how they find this row.
 */
export async function createOrder(input: CreateOrderInput): Promise<Order> {
  const [row] = await db
    .insert(orders)
    .values({
      reference: input.reference,
      customerId: input.customerId,
      userId: input.userId ?? null,
      salesAgentId: input.salesAgentId ?? null,
      termId: input.termId ?? null,
      amountKobo: input.amountKobo,
      currency: input.currency ?? "NGN",
      source: input.source ?? "website",
      providerReference: input.providerReference ?? null,
      authorizationUrl: input.authorizationUrl ?? null,
      metadata: input.metadata ?? {},
    })
    .onConflictDoUpdate({
      target: orders.reference,
      set: {
        providerReference: input.providerReference ?? null,
        authorizationUrl: input.authorizationUrl ?? null,
        updatedAt: new Date(),
      },
    })
    .returning();
  return row;
}

export async function findOrderByReference(reference: string): Promise<Order | null> {
  const [row] = await db.select().from(orders).where(eq(orders.reference, reference)).limit(1);
  return row ?? null;
}

export async function findOrderById(id: string): Promise<Order | null> {
  const [row] = await db.select().from(orders).where(eq(orders.id, id)).limit(1);
  return row ?? null;
}

/**
 * Mark an order paid — the single gate that turns a payment into a purchase.
 *
 * Returns `{ order, alreadyPaid }` so a caller can tell "I did this" from "my
 * partner request beat me to it" and skip provisioning on the second call. The
 * update is guarded on `status <> 'paid'` so the transition can only happen once,
 * even under two concurrent requests.
 */
export async function markOrderPaid(
  id: string,
  { providerReference, paidAt }: { providerReference?: string | null; paidAt?: Date | null }
): Promise<{ order: Order; alreadyPaid: boolean }> {
  const updated = await db
    .update(orders)
    .set({
      status: "paid",
      paidAt: paidAt ?? new Date(),
      ...(providerReference ? { providerReference } : {}),
      updatedAt: new Date(),
    })
    .where(and(eq(orders.id, id), sql`${orders.status} <> 'paid'`))
    .returning();

  if (updated[0]) return { order: updated[0], alreadyPaid: false };

  // Either it was already paid, or the id does not exist. Either way the caller
  // gets the current row and the "already" flag it needs.
  const existing = await findOrderById(id);
  if (!existing) throw new Error(`No order with id ${id}.`);
  return { order: existing, alreadyPaid: true };
}

export async function markOrderFailed(id: string, reason: string): Promise<void> {
  await db
    .update(orders)
    .set({ status: "failed", failureReason: reason, updatedAt: new Date() })
    .where(and(eq(orders.id, id), sql`${orders.status} = 'pending'`));
}

export async function attachOrderProvisioning(
  id: string,
  { subscriptionId, termId }: { subscriptionId?: string | null; termId?: string | null }
): Promise<void> {
  await db
    .update(orders)
    .set({
      ...(subscriptionId ? { subscriptionId } : {}),
      ...(termId ? { termId } : {}),
      updatedAt: new Date(),
    })
    .where(eq(orders.id, id));
}

export interface OrderRowForList extends Order {
  customerName: string | null;
  customerEmail: string | null;
  agentName: string | null;
  termName: string | null;
}

/** Internal listing, joined to the names an operator actually recognises. */
export async function listOrders({
  statuses,
  limit = 100,
}: { statuses?: OrderStatus[]; limit?: number } = {}): Promise<OrderRowForList[]> {
  const where =
    statuses && statuses.length > 0 ? inArray(orders.status, statuses) : undefined;

  const rows = await db
    .select({
      order: orders,
      customerName: customers.fullName,
      customerEmail: customers.email,
      agentName: salesAgents.name,
      termName: terms.name,
    })
    .from(orders)
    .leftJoin(customers, eq(orders.customerId, customers.id))
    .leftJoin(salesAgents, eq(orders.salesAgentId, salesAgents.id))
    .leftJoin(terms, eq(orders.termId, terms.id))
    .where(where)
    .orderBy(desc(orders.createdAt))
    .limit(limit);

  return rows.map((r) => ({
    ...r.order,
    customerName: r.customerName,
    customerEmail: r.customerEmail,
    agentName: r.agentName,
    termName: r.termName,
  }));
}

export async function orderTotals(): Promise<{ paidKobo: number; paidCount: number }> {
  const [row] = await db
    .select({
      total: sql<string>`COALESCE(SUM(${orders.amountKobo}), 0)`,
      paid: count(),
    })
    .from(orders)
    .where(eq(orders.status, "paid"));
  return { paidKobo: Number(row?.total ?? 0), paidCount: Number(row?.paid ?? 0) };
}
